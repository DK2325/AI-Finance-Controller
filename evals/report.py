"""Report generation: JSON, a markdown table, and the README rewrite.

The README metrics table is regenerated between marker comments and must never be
hand-edited -- a hand-edited number is one nobody can reproduce, which is the opposite
of what this project claims.
"""

from __future__ import annotations

import json
from pathlib import Path

from evals.curve import RiskCoverageCurve
from evals.metrics import Batch, Score, confusion_by_case_type
from evals.models import Prediction

MARKER_START = "<!-- METRICS:START -->"
MARKER_END = "<!-- METRICS:END -->"

HELD_OUT_CASES = ("tds_deducted", "refund_netted")


def rupees(paise: int) -> str:
    return f"{paise / 100:,.2f}"


def build_report(
    run_id: str,
    batch_dir: str,
    predictions: list[Prediction],
    batch: Batch,
    score: Score,
    curve: RiskCoverageCurve,
) -> dict:
    confusion = confusion_by_case_type(predictions, batch, score.threshold)
    return {
        "run_id": run_id,
        "batch_dir": batch_dir,
        "score": score.as_dict(),
        "curve": curve.as_dict(),
        "confusion_by_case_type": {
            "seen": {k: v for k, v in sorted(confusion.items()) if k not in HELD_OUT_CASES},
            "held_out": {k: v for k, v in sorted(confusion.items()) if k in HELD_OUT_CASES},
        },
    }


def markdown_table(report: dict) -> str:
    """The block written into the README between the markers."""
    s = report["score"]
    curve = report["curve"]

    lines = [
        f"_Run `{report['run_id']}` on `{report['batch_dir']}`. "
        "Regenerated by `ledgerloop eval`; do not hand-edit._",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Auto-match rate (coverage) | {s['coverage']:.2%} |",
        f"| Precision on auto-matched | {s['precision']:.2%} |",
        f"| Recall of true links | {s['recall']:.2%} |",
        f"| Money-weighted precision | {s['money_weighted_precision']:.4%} |",
        f"| Money error ratio (Rs wrong / Rs at stake) | {s['money_error_ratio']:.4%} |",
        f"| Orphan refusal rate | {s['orphan_refusal_rate']:.2%} |",
        f"| Rs at stake | {rupees(s['total_money'])} |",
        f"| Rs incorrectly matched | {rupees(s['wrong_money'])} |",
        f"| False auto-matches | {s['n_false_positives']} |",
        f"| Risk-coverage curve points | {curve['n_points']}"
        f"{' (degenerate)' if curve['is_degenerate'] else ''} |",
        "",
        "**Per-case-type**",
        "",
        "| case_type | total | matched | missed | refused |",
        "|---|---|---|---|---|",
    ]

    for group, label in (("seen", ""), ("held_out", " *(held out)*")):
        for case, counts in report["confusion_by_case_type"][group].items():
            lines.append(
                f"| `{case}`{label} | {counts['total']} | {counts['matched']} | "
                f"{counts['missed']} | {counts['refused']} |"
            )

    return "\n".join(lines)


def write_readme_table(readme: Path, table: str) -> None:
    """Replace the block between the markers, leaving the rest of the README untouched."""
    text = readme.read_text(encoding="utf-8")

    if MARKER_START not in text or MARKER_END not in text:
        raise ValueError(
            f"{readme} is missing the {MARKER_START} / {MARKER_END} markers; "
            "refusing to guess where the table goes"
        )

    head, _, rest = text.partition(MARKER_START)
    _, _, tail = rest.partition(MARKER_END)

    readme.write_text(
        f"{head}{MARKER_START}\n{table}\n{MARKER_END}{tail}",
        encoding="utf-8",
        newline="\n",
    )


def save_report(path: Path | str, report: dict) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        handle.write(json.dumps(report, indent=2, sort_keys=True) + "\n")
